import { z } from 'zod';
import { registerSchema } from './auth.js';
import { createBookingSchema, type BookingResult } from './bookings.js';

// Maximum value of a Postgres INTEGER: larger ids would fail in the database.
const MAX_DB_INT = 2_147_483_647;

// MH-07: the staff search hikers by name, phone or email. Two characters avoid listing everyone.
export const MIN_HIKER_SEARCH_LENGTH = 2;

export const hikerSearchQuerySchema = z.object({
  search: z.string().trim().min(MIN_HIKER_SEARCH_LENGTH),
});
export type HikerSearchQuery = z.infer<typeof hikerSearchQuerySchema>;

// A hiker as the staff see it. A temporary hiker has no account: no email and no web access.
export interface HikerProfile {
  id: number;
  fullName: string;
  email: string | null;
  phone: string | null;
  notes: string | null;
  emergencyContact: string | null;
  temporary: boolean;
}

// Quick entry: only the name, the phone is optional. The hiker cannot log in.
export const temporaryHikerSchema = registerSchema
  .pick({ fullName: true })
  .extend({ phone: registerSchema.shape.phone.optional() });
export type TemporaryHikerInput = z.infer<typeof temporaryHikerSchema>;

// Full profile: the same data as the web registration, but the password is generated by the API.
export const newHikerAccountSchema = registerSchema.omit({ password: true });
export type NewHikerAccountInput = z.infer<typeof newHikerAccountSchema>;

// Who the booking is for: an existing hiker, a new temporary hiker or a new regular hiker.
export const staffBookingHikerSchema = z.discriminatedUnion('kind', [
  z.object({ kind: z.literal('EXISTING'), hikerId: z.number().int().positive().max(MAX_DB_INT) }),
  temporaryHikerSchema.extend({ kind: z.literal('TEMPORARY') }),
  newHikerAccountSchema.extend({ kind: z.literal('ACCOUNT') }),
]);
export type StaffBookingHiker = z.infer<typeof staffBookingHikerSchema>;

// The only time limit for the staff is the start of the slot, checked by the API.
// The requirements are those of a hiker's booking: with MH-05 they become a list, one entry per
// subset of the party with its own allergies flag.
export const createStaffBookingSchema = createBookingSchema.extend({
  hiker: staffBookingHikerSchema,
});
export type CreateStaffBookingInput = z.infer<typeof createStaffBookingSchema>;

export interface StaffBookingResult extends BookingResult {
  hiker: HikerProfile;
  // Only when a regular hiker was created: the staff tell it to the hiker, who must change it
  // at the next login.
  generatedPassword?: string;
}
